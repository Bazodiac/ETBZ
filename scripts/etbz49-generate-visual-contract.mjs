/** Deterministic literal emission: sorted keys, LF newlines, no Date, no Math.random. */
function literal(value, indent = 0) {
  const pad = '  '.repeat(indent);
  const padInner = '  '.repeat(indent + 1);
  if (value === null) return 'null';
  if (typeof value === 'string') return JSON.stringify(value);
  if (typeof value === 'number' || typeof value === 'boolean') return String(value);
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]';
    const scalarOnly = value.every((entry) => entry === null || typeof entry !== 'object');
    if (scalarOnly) {
      const inline = `[${value.map((entry) => literal(entry)).join(', ')}]`;
      if (inline.length + pad.length <= 96) return inline;
    }
    return `[\n${value
      .map((entry) => `${padInner}${literal(entry, indent + 1)},`)
      .join('\n')}\n${pad}]`;
  }
  const keys = Object.keys(value);
  if (keys.length === 0) return '{}';
  return `{\n${keys
    .map((key) => `${padInner}${JSON.stringify(key)}: ${literal(value[key], indent + 1)},`)
    .join('\n')}\n${pad}}`;
}

const header = (title, body) =>
  [
    '// =============================================================================',
    `// ${title}`,
    '//',
    ...body.map((line) => (line === '' ? '//' : `// ${line}`)),
    '//',
    '// GENERATED by scripts/etbz49-generate-visual-contract.mjs from',
    '// assets/visual-system-v1/. Do not edit by hand - edit the asset and re-run.',
    '// =============================================================================',
    '',
  ].join('\n');

const emit = (name, contents) => {
  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(resolve(OUT_DIR, name), contents.replace(/\r\n/g, '\n'), 'utf8');
  return name;
};

