#!/usr/bin/env node
// =============================================================================
// ETBZ-49 - project the canonical visual assets into TypeScript.
//
// `src/application/visual` may not touch the filesystem: the dependency-direction
// guard restricts the application layer to `zod` and relative imports, which is
// what keeps the layer runtime-agnostic and the contract a pure value. The
// canonical contract nevertheless LIVES in `assets/visual-system-v1/*.json`,
// because those files are the recovered artefacts whose hashes the provenance
// record names.
//
// This script is the bridge, and it is deliberately a projection rather than a
// transformation: every field is copied, none is computed. `npm run
// etbz49:contract:check` re-runs it into a temporary directory and requires a
// byte-identical result, so the committed TypeScript cannot drift away from the
// assets it claims to carry - in either direction.
//
//   node scripts/etbz49-generate-visual-contract.mjs            # write
//   node scripts/etbz49-generate-visual-contract.mjs --out DIR  # write elsewhere
// =============================================================================

